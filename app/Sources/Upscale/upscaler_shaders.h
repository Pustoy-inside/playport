#ifndef PLAYPORT_UPSCALER_SHADERS_H
#define PLAYPORT_UPSCALER_SHADERS_H

static const char pp_upscaler_shaders[] =
    "#include <metal_stdlib>\n"
    "using namespace metal;\n"
    "\n"
    "struct PPVertexOut {\n"
    "    float4 position [[position]];\n"
    "};\n"
    "\n"
    "// One triangle over the whole target: (-1,-1), (3,-1), (-1,3).\n"
    "vertex PPVertexOut pp_fullscreen(uint vid [[vertex_id]]) {\n"
    "    float2 p = float2(float((vid << 1) & 2u), float(vid & 2u));\n"
    "    PPVertexOut out;\n"
    "    out.position = float4(p * 2.0 - 1.0, 0.0, 1.0);\n"
    "    return out;\n"
    "}\n"
    "\n"
    "// The source as it is, pixel for pixel (the same size as the target).\n"
    "fragment float4 pp_copy(PPVertexOut in [[stage_in]], texture2d<float> src [[texture(0)]]) {\n"
    "    return float4(src.read(uint2(in.position.xy)).rgb, 1.0);\n"
    "}\n"
    "\n"
    "// The source filtered to the target's size (nothing to upscale).\n"
    "fragment float4 pp_bilinear(PPVertexOut in [[stage_in]], texture2d<float> src [[texture(0)]],\n"
    "                            constant float2 &inverseTarget [[buffer(0)]]) {\n"
    "    constexpr sampler s(coord::normalized, address::clamp_to_edge, filter::linear);\n"
    "    return float4(src.sample(s, in.position.xy * inverseTarget).rgb, 1.0);\n"
    "}\n"
    "\n"
    "// ---------------------------------------------------------------------------\n"
    "// FSR 1: EASU and RCAS, ported from AMD's ffx_fsr1.h (the non-packed 32-bit\n"
    "// version, FidelityFX-FSR a21ffb8f), with its approximations kept.\n"
    "\n"
    "struct PPEasuConstants {\n"
    "    float4 con0;\n"
    "    float4 con1;\n"
    "    float4 con2;\n"
    "    float4 con3;\n"
    "};\n"
    "\n"
    "static inline float pp_rcp_lo(float a) { return as_type<float>(0x7ef07ebbu - as_type<uint>(a)); }\n"
    "static inline float pp_rsq_lo(float a) { return as_type<float>(0x5f347d74u - (as_type<uint>(a) >> 1u)); }\n"
    "\n"
    "// FsrEasuSetF: direction and length from the '+' around c, weighted bilinearly.\n"
    "static inline void pp_easu_set(thread float2 &dir, thread float &len, float w,\n"
    "                               float lA, float lB, float lC, float lD, float lE) {\n"
    "    float dc = lD - lC;\n"
    "    float cb = lC - lB;\n"
    "    float lenX = pp_rcp_lo(max(fabs(dc), fabs(cb)));\n"
    "    float dirX = lD - lB;\n"
    "    dir.x += dirX * w;\n"
    "    lenX = saturate(fabs(dirX) * lenX);\n"
    "    lenX *= lenX;\n"
    "    len += lenX * w;\n"
    "    float ec = lE - lC;\n"
    "    float ca = lC - lA;\n"
    "    float lenY = pp_rcp_lo(max(fabs(ec), fabs(ca)));\n"
    "    float dirY = lE - lA;\n"
    "    dir.y += dirY * w;\n"
    "    lenY = saturate(fabs(dirY) * lenY);\n"
    "    lenY *= lenY;\n"
    "    len += lenY * w;\n"
    "}\n"
    "\n"
    "// FsrEasuTapF: one tap of the approximated, windowed Lanczos 2 kernel.\n"
    "static inline void pp_easu_tap(thread float3 &aC, thread float &aW, float2 off, float2 dir, float2 len,\n"
    "                               float lob, float clp, float3 c) {\n"
    "    float2 v;\n"
    "    v.x = (off.x * (dir.x)) + (off.y * dir.y);\n"
    "    v.y = (off.x * (-dir.y)) + (off.y * dir.x);\n"
    "    v *= len;\n"
    "    float d2 = v.x * v.x + v.y * v.y;\n"
    "    d2 = min(d2, clp);\n"
    "    float wB = (2.0 / 5.0) * d2 + (-1.0);\n"
    "    float wA = lob * d2 + (-1.0);\n"
    "    wB *= wB;\n"
    "    wA *= wA;\n"
    "    wB = (25.0 / 16.0) * wB + (-(25.0 / 16.0 - 1.0));\n"
    "    float w = wB * wA;\n"
    "    aC += c * w;\n"
    "    aW += w;\n"
    "}\n"
    "\n"
    "// FsrEasuF: Edge Adaptive Spatial Upsampling, one output pixel.\n"
    "fragment float4 pp_easu(PPVertexOut in [[stage_in]], texture2d<float> src [[texture(0)]],\n"
    "                        constant PPEasuConstants &con [[buffer(0)]]) {\n"
    "    constexpr sampler s(coord::normalized, address::clamp_to_edge, filter::nearest);\n"
    "    float2 pp = floor(in.position.xy) * con.con0.xy + con.con0.zw;\n"
    "    float2 fp = floor(pp);\n"
    "    pp -= fp;\n"
    "    //    b c\n"
    "    //  e f g h\n"
    "    //  i j k l\n"
    "    //    n o\n"
    "    float2 p0 = fp * con.con1.xy + con.con1.zw;\n"
    "    float2 p1 = p0 + con.con2.xy;\n"
    "    float2 p2 = p0 + con.con2.zw;\n"
    "    float2 p3 = p0 + con.con3.xy;\n"
    "    float4 bczzR = src.gather(s, p0, int2(0), component::x);\n"
    "    float4 bczzG = src.gather(s, p0, int2(0), component::y);\n"
    "    float4 bczzB = src.gather(s, p0, int2(0), component::z);\n"
    "    float4 ijfeR = src.gather(s, p1, int2(0), component::x);\n"
    "    float4 ijfeG = src.gather(s, p1, int2(0), component::y);\n"
    "    float4 ijfeB = src.gather(s, p1, int2(0), component::z);\n"
    "    float4 klhgR = src.gather(s, p2, int2(0), component::x);\n"
    "    float4 klhgG = src.gather(s, p2, int2(0), component::y);\n"
    "    float4 klhgB = src.gather(s, p2, int2(0), component::z);\n"
    "    float4 zzonR = src.gather(s, p3, int2(0), component::x);\n"
    "    float4 zzonG = src.gather(s, p3, int2(0), component::y);\n"
    "    float4 zzonB = src.gather(s, p3, int2(0), component::z);\n"
    "    // Luma times 2.\n"
    "    float4 bczzL = bczzB * 0.5 + (bczzR * 0.5 + bczzG);\n"
    "    float4 ijfeL = ijfeB * 0.5 + (ijfeR * 0.5 + ijfeG);\n"
    "    float4 klhgL = klhgB * 0.5 + (klhgR * 0.5 + klhgG);\n"
    "    float4 zzonL = zzonB * 0.5 + (zzonR * 0.5 + zzonG);\n"
    "    float bL = bczzL.x;\n"
    "    float cL = bczzL.y;\n"
    "    float iL = ijfeL.x;\n"
    "    float jL = ijfeL.y;\n"
    "    float fL = ijfeL.z;\n"
    "    float eL = ijfeL.w;\n"
    "    float kL = klhgL.x;\n"
    "    float lL = klhgL.y;\n"
    "    float hL = klhgL.z;\n"
    "    float gL = klhgL.w;\n"
    "    float oL = zzonL.z;\n"
    "    float nL = zzonL.w;\n"
    "    float2 dir = float2(0.0);\n"
    "    float len = 0.0;\n"
    "    pp_easu_set(dir, len, (1.0 - pp.x) * (1.0 - pp.y), bL, eL, fL, gL, jL);\n"
    "    pp_easu_set(dir, len, pp.x * (1.0 - pp.y), cL, fL, gL, hL, kL);\n"
    "    pp_easu_set(dir, len, (1.0 - pp.x) * pp.y, fL, iL, jL, kL, nL);\n"
    "    pp_easu_set(dir, len, pp.x * pp.y, gL, jL, kL, lL, oL);\n"
    "    float2 dir2 = dir * dir;\n"
    "    float dirR = dir2.x + dir2.y;\n"
    "    bool zro = dirR < (1.0 / 32768.0);\n"
    "    dirR = pp_rsq_lo(dirR);\n"
    "    dirR = zro ? 1.0 : dirR;\n"
    "    dir.x = zro ? 1.0 : dir.x;\n"
    "    dir *= float2(dirR);\n"
    "    len = len * 0.5;\n"
    "    len *= len;\n"
    "    float stretch = (dir.x * dir.x + dir.y * dir.y) * pp_rcp_lo(max(fabs(dir.x), fabs(dir.y)));\n"
    "    float2 len2 = float2(1.0 + (stretch - 1.0) * len, 1.0 + (-0.5) * len);\n"
    "    float lob = 0.5 + ((1.0 / 4.0 - 0.04) - 0.5) * len;\n"
    "    float clp = pp_rcp_lo(lob);\n"
    "    float3 f4 = float3(ijfeR.z, ijfeG.z, ijfeB.z);\n"
    "    float3 g4 = float3(klhgR.w, klhgG.w, klhgB.w);\n"
    "    float3 j4 = float3(ijfeR.y, ijfeG.y, ijfeB.y);\n"
    "    float3 k4 = float3(klhgR.x, klhgG.x, klhgB.x);\n"
    "    float3 min4 = min(min(min(f4, g4), j4), k4);\n"
    "    float3 max4 = max(max(max(f4, g4), j4), k4);\n"
    "    float3 aC = float3(0.0);\n"
    "    float aW = 0.0;\n"
    "    pp_easu_tap(aC, aW, float2( 0.0, -1.0) - pp, dir, len2, lob, clp, float3(bczzR.x, bczzG.x, bczzB.x)); // b\n"
    "    pp_easu_tap(aC, aW, float2( 1.0, -1.0) - pp, dir, len2, lob, clp, float3(bczzR.y, bczzG.y, bczzB.y)); // c\n"
    "    pp_easu_tap(aC, aW, float2(-1.0,  1.0) - pp, dir, len2, lob, clp, float3(ijfeR.x, ijfeG.x, ijfeB.x)); // i\n"
    "    pp_easu_tap(aC, aW, float2( 0.0,  1.0) - pp, dir, len2, lob, clp, float3(ijfeR.y, ijfeG.y, ijfeB.y)); // j\n"
    "    pp_easu_tap(aC, aW, float2( 0.0,  0.0) - pp, dir, len2, lob, clp, float3(ijfeR.z, ijfeG.z, ijfeB.z)); // f\n"
    "    pp_easu_tap(aC, aW, float2(-1.0,  0.0) - pp, dir, len2, lob, clp, float3(ijfeR.w, ijfeG.w, ijfeB.w)); // e\n"
    "    pp_easu_tap(aC, aW, float2( 1.0,  1.0) - pp, dir, len2, lob, clp, float3(klhgR.x, klhgG.x, klhgB.x)); // k\n"
    "    pp_easu_tap(aC, aW, float2( 2.0,  1.0) - pp, dir, len2, lob, clp, float3(klhgR.y, klhgG.y, klhgB.y)); // l\n"
    "    pp_easu_tap(aC, aW, float2( 2.0,  0.0) - pp, dir, len2, lob, clp, float3(klhgR.z, klhgG.z, klhgB.z)); // h\n"
    "    pp_easu_tap(aC, aW, float2( 1.0,  0.0) - pp, dir, len2, lob, clp, float3(klhgR.w, klhgG.w, klhgB.w)); // g\n"
    "    pp_easu_tap(aC, aW, float2( 1.0,  2.0) - pp, dir, len2, lob, clp, float3(zzonR.z, zzonG.z, zzonB.z)); // o\n"
    "    pp_easu_tap(aC, aW, float2( 0.0,  2.0) - pp, dir, len2, lob, clp, float3(zzonR.w, zzonG.w, zzonB.w)); // n\n"
    "    // Normalize and dering.\n"
    "    float3 pix = min(max4, max(min4, aC * float3(1.0 / aW)));\n"
    "    return float4(pix, 1.0);\n"
    "}\n"
    "\n"
    "// FsrRcasF's limiters for one channel: max(-hitMin, hitMax). AMD's rcp of 0\n"
    "// (a black ring for hitMin, a white one for hitMax) makes a NaN there, which\n"
    "// its max drops; a term that would be one is left out here instead.\n"
    "static inline float pp_rcas_lobe(float mn4, float mx4, float e) {\n"
    "    float minDen = 4.0 * mx4;\n"
    "    float maxDen = 4.0 * mn4 + (-1.0 * 4.0);\n"
    "    float lowest = -1.0e30;\n"
    "    float hitMin = minDen > 0.0 ? -(min(mn4, e) / minDen) : lowest;\n"
    "    float hitMax = maxDen < 0.0 ? (1.0 - max(mx4, e)) / maxDen : lowest;\n"
    "    return max(hitMin, hitMax);\n"
    "}\n"
    "\n"
    "// FsrRcasF: Robust Contrast Adaptive Sharpening, without the noise removal\n"
    "// (FSR_RCAS_DENOISE off, as by default). sharpness is exp2(-stops).\n"
    "fragment float4 pp_rcas(PPVertexOut in [[stage_in]], texture2d<float> src [[texture(0)]],\n"
    "                        constant float &sharpness [[buffer(0)]]) {\n"
    "    int2 sp = int2(in.position.xy);\n"
    "    int2 hi = int2(int(src.get_width()) - 1, int(src.get_height()) - 1);\n"
    "    //    b\n"
    "    //  d e f\n"
    "    //    h\n"
    "    float3 b = src.read(uint2(clamp(sp + int2( 0, -1), int2(0), hi))).rgb;\n"
    "    float3 d = src.read(uint2(clamp(sp + int2(-1,  0), int2(0), hi))).rgb;\n"
    "    float3 e = src.read(uint2(sp)).rgb;\n"
    "    float3 f = src.read(uint2(clamp(sp + int2( 1,  0), int2(0), hi))).rgb;\n"
    "    float3 h = src.read(uint2(clamp(sp + int2( 0,  1), int2(0), hi))).rgb;\n"
    "    // Min and max of the ring.\n"
    "    float3 mn4 = min(min(min(b, d), f), h);\n"
    "    float3 mx4 = max(max(max(b, d), f), h);\n"
    "    // Limiters (pp_rcas_lobe), the largest of the three channels', clamped.\n"
    "    float3 lobeRGB = float3(pp_rcas_lobe(mn4.r, mx4.r, e.r), pp_rcas_lobe(mn4.g, mx4.g, e.g),\n"
    "                            pp_rcas_lobe(mn4.b, mx4.b, e.b));\n"
    "    float lobe = max(-(0.25 - (1.0 / 16.0)), min(max(max(lobeRGB.r, lobeRGB.g), lobeRGB.b), 0.0)) * sharpness;\n"
    "    // Resolve.\n"
    "    float rcpL = 1.0 / (4.0 * lobe + 1.0);\n"
    "    float3 pix = (lobe * b + lobe * d + lobe * h + lobe * f + e) * rcpL;\n"
    "    return float4(pix, 1.0);\n"
    "}\n"
    "\n";

#endif
